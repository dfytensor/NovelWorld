$files = if (Test-Path $Path -PathType Container) { Get-ChildItem $Path -Include *.md,*.txt -Recurse -File | Where-Object { $_.Name -notmatch '^00' } } else { @((Get-Item $Path)) }
$rows = @()
foreach ($f in $files) {
  $t = [System.IO.File]::ReadAllText($f.FullName, [System.Text.Encoding]::UTF8)
  $body = ($t -split '^# .+', 2)[1]; if (-not $body) { $body = $t }
  $kw = ($body -replace '\s', '').Length / 1000.0
  if ($kw -lt 0.2) { continue }
  foreach ($k in $tags.Keys) {
    $n = ([regex]::Matches($body, $tags[$k])).Count
    if ($n -gt 0) { $rows += [pscustomobject]@{ File = $f.Name; Tag = $k; Hits = $n; Density = [math]::Round($n / $kw, 2) } }
  }
}
$rows | Sort-Object File, @{e='Density';d=$true} | Format-Table -AutoSize
$summary = $rows | Group-Object Tag | ForEach-Object {
  [pscustomobject]@{ Tag = $_.Name; Files = $_.Count; TotalHits = ($_.Group | Measure-Object Hits -Sum).Sum; MaxDensity = ($_.Group | Measure-Object Density -Maximum).Maximum }
} | Sort-Object TotalHits -Descending
"=== 词签总览 ==="
$summary | Format-Table -AutoSize
"检出 $($summary.Count)/$($tags.Count) 种情绪价值 | 未检出: $((($tags.Keys | Where-Object { $_ -notin $summary.Tag }) -join ', '))"
